  function triadWords(n, female) {
    const out = [];
    const h = Math.floor(n / 100), t = Math.floor((n % 100) / 10), o = n % 10;
    if (h) out.push(HUNDREDS[h]);
    if (t === 1) out.push(TEENS[o]);
    else {
      if (t) out.push(TENS[t]);
      if (o) out.push((female ? ONES_F : ONES_M)[o]);
    }
    return out;
  }

  /** «8 400 000,55» → «восемь миллионов четыреста тысяч рублей 55 копеек». */
  function moneyWords(v) {
    if (v == null || v === '' || !isFinite(v)) return '';
    const total = Math.round(Math.abs(Number(v)) * 100);
    const rub = Math.floor(total / 100);
    const kop = total % 100;

    const scales = [
      { one: 'миллиард', few: 'миллиарда', many: 'миллиардов', female: false },
      { one: 'миллион', few: 'миллиона', many: 'миллионов', female: false },
      { one: 'тысяча', few: 'тысячи', many: 'тысяч', female: true },
      { one: 'рубль', few: 'рубля', many: 'рублей', female: false }
    ];

    const triads = [
      Math.floor(rub / 1e9) % 1000,
      Math.floor(rub / 1e6) % 1000,
      Math.floor(rub / 1e3) % 1000,
      rub % 1000
    ];

    const words = [];
    let started = false;
    for (let i = 0; i < 4; i++) {
      const n = triads[i], s = scales[i];
      const last = i === 3;
      if (!n && !last) continue;
      if (n || (last && !started)) {
        if (n || last) words.push(...triadWords(n, s.female));
      }
      if (n || last) {
        words.push(plural(n, s.one, s.few, s.many));
        started = true;
      }
    }

    // Ноль рублей триадами не набирается: 0 % 1000 === 0 и слов не даёт.
    let text = words.filter(Boolean).join(' ');
    if (!rub) text = 'ноль ' + plural(0, 'рубль', 'рубля', 'рублей');

    const sign = Number(v) < 0 ? 'минус ' : '';
    return sign + text[0].toUpperCase() + text.slice(1) + ' ' +
      String(kop).padStart(2, '0') + ' ' + plural(kop, 'копейка', 'копейки', 'копеек');
  }

